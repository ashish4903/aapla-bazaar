export function translate(lang, key, vars = {}) {
  let text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (text.includes('|')) {
    const [one, many] = text.split('|');
    text = vars.n === 1 ? one : many;
  }
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
